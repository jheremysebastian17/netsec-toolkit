// Firewall rule generator for iptables, nftables and UFW. Pure functions, no DOM.

export const SERVICES = [
  { id: 'ssh', name: 'SSH', ports: [[22, 'tcp']] },
  { id: 'http', name: 'HTTP', ports: [[80, 'tcp']] },
  { id: 'https', name: 'HTTPS', ports: [[443, 'tcp']] },
  { id: 'dns', name: 'DNS', ports: [[53, 'tcp'], [53, 'udp']] },
  { id: 'dhcp', name: 'DHCP server', ports: [[67, 'udp']] },
  { id: 'smtp', name: 'SMTP', ports: [[25, 'tcp']] },
  { id: 'mysql', name: 'MySQL', ports: [[3306, 'tcp']] },
  { id: 'smb', name: 'SMB', ports: [[445, 'tcp']] },
  { id: 'rdp', name: 'RDP', ports: [[3389, 'tcp']] },
];

// opts: { services: ['ssh', ...], custom: [{port, proto}], sshSource: 'CIDR' | '', icmp: bool }
export function collectRules({ services = [], custom = [], sshSource = '' }) {
  const rules = [];
  for (const s of SERVICES) {
    if (!services.includes(s.id)) continue;
    for (const [port, proto] of s.ports) rules.push({ port, proto, name: s.name, source: s.id === 'ssh' ? sshSource : '' });
  }
  for (const c of custom) rules.push({ port: c.port, proto: c.proto, name: `Custom ${c.port}/${c.proto}`, source: '' });
  return rules;
}

export function toIptables(opts) {
  const lines = [
    '#!/usr/bin/env bash',
    '# Generated by NetSec Toolkit. Run as root from a console session when possible.',
    'set -e',
    'iptables -F INPUT',
    'iptables -A INPUT -i lo -j ACCEPT',
    'iptables -A INPUT -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT',
    'iptables -A INPUT -m conntrack --ctstate INVALID -j DROP',
  ];
  if (opts.icmp) lines.push('iptables -A INPUT -p icmp --icmp-type echo-request -j ACCEPT');
  for (const r of collectRules(opts)) {
    lines.push(`iptables -A INPUT -p ${r.proto} --dport ${r.port}${r.source ? ` -s ${r.source}` : ''} -m comment --comment "${r.name}" -j ACCEPT`);
  }
  // Default-drop policies go last so an SSH session is not cut before its allow rule exists.
  lines.push('iptables -P INPUT DROP', 'iptables -P FORWARD DROP', 'iptables -P OUTPUT ACCEPT');
  return lines.join('\n');
}

export function toNftables(opts) {
  const body = [
    '    iif "lo" accept',
    '    ct state established,related accept',
    '    ct state invalid drop',
    // IPv6 neighbour discovery must stay open or IPv6 networking breaks.
    '    icmpv6 type { nd-neighbor-solicit, nd-neighbor-advert, nd-router-advert } accept',
  ];
  if (opts.icmp) body.push('    icmp type echo-request accept', '    icmpv6 type echo-request accept');
  for (const r of collectRules(opts)) {
    body.push(`    ${r.source ? `ip saddr ${r.source} ` : ''}${r.proto} dport ${r.port} accept comment "${r.name}"`);
  }
  return [
    '#!/usr/sbin/nft -f',
    '# Generated by NetSec Toolkit. Load with: nft -f rules.nft',
    'flush ruleset',
    '',
    'table inet filter {',
    '  chain input {',
    '    type filter hook input priority 0; policy drop;',
    ...body,
    '  }',
    '  chain forward {',
    '    type filter hook forward priority 0; policy drop;',
    '  }',
    '  chain output {',
    '    type filter hook output priority 0; policy accept;',
    '  }',
    '}',
  ].join('\n');
}

export function toUfw(opts) {
  const lines = [
    '#!/usr/bin/env bash',
    '# Generated by NetSec Toolkit. Run as root.',
    'set -e',
    'ufw --force reset',
    'ufw default deny incoming',
    'ufw default allow outgoing',
  ];
  for (const r of collectRules(opts)) {
    lines.push(r.source
      ? `ufw allow from ${r.source} to any port ${r.port} proto ${r.proto} comment '${r.name}'`
      : `ufw allow ${r.port}/${r.proto} comment '${r.name}'`);
  }
  if (!opts.icmp) lines.push('# Note: UFW allows ICMP echo by default; edit /etc/ufw/before.rules to block it.');
  lines.push('ufw --force enable', 'ufw status verbose');
  return lines.join('\n');
}
