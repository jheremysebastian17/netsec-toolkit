// Uptime checks from the browser + cron script generator.

export function normalizeUrl(raw) {
  let s = String(raw).trim();
  if (!s) return null;
  if (!/^[a-z][a-z0-9+.-]*:\/\//i.test(s)) s = 'https://' + s;
  const u = new URL(s); // throws on invalid input
  if (!/^https?:$/.test(u.protocol)) throw new Error('Only http and https URLs are supported');
  return u.href;
}

// no-cors cannot read the status code, so this only proves the host answered over HTTP(S).
export async function checkUrl(url, timeoutMs = 8000) {
  const start = performance.now();
  try {
    await fetch(url, { mode: 'no-cors', cache: 'no-store', signal: AbortSignal.timeout(timeoutMs) });
    return { url, up: true, ms: Math.round(performance.now() - start) };
  } catch (e) {
    return { url, up: false, ms: Math.round(performance.now() - start), error: e.name === 'TimeoutError' ? 'Timed out' : 'Unreachable' };
  }
}

const sq = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`;

export function buildMonitorScript({ urls, channel = 'none', discordWebhook = '', telegramToken = '', telegramChat = '' }) {
  if (!urls.length) throw new Error('Add at least one URL');
  let notify = '  echo "ALERT: $1"';
  let config = '';
  if (channel === 'discord') {
    config = `DISCORD_WEBHOOK="\${DISCORD_WEBHOOK:-}"\n[ -z "$DISCORD_WEBHOOK" ] && DISCORD_WEBHOOK=${sq(discordWebhook || 'https://discord.com/api/webhooks/CHANGE_ME')}`;
    notify = `  curl -s -H 'Content-Type: application/json' -d "{\\"content\\": \\"$1\\"}" "$DISCORD_WEBHOOK" >/dev/null`;
  } else if (channel === 'telegram') {
    config = `TELEGRAM_TOKEN="\${TELEGRAM_TOKEN:-}"\n[ -z "$TELEGRAM_TOKEN" ] && TELEGRAM_TOKEN=${sq(telegramToken || 'CHANGE_ME')}\nTELEGRAM_CHAT=${sq(telegramChat || 'CHANGE_ME')}`;
    notify = `  curl -s "https://api.telegram.org/bot$TELEGRAM_TOKEN/sendMessage" --data-urlencode "chat_id=$TELEGRAM_CHAT" --data-urlencode "text=$1" >/dev/null`;
  }
  return `#!/usr/bin/env bash
# Uptime monitor - generated by NetSec Toolkit.
# Alerts only when a service changes state (UP -> DOWN or DOWN -> UP).
# Schedule every 5 minutes with: crontab -e
#   */5 * * * * /path/to/monitor.sh >> /var/log/uptime-monitor.log 2>&1

URLS=(
${urls.map((u) => `  ${sq(u)}`).join('\n')}
)
${config}
STATE_DIR="\${STATE_DIR:-$HOME/.cache/uptime-monitor}"
mkdir -p "$STATE_DIR"

notify() {
${notify}
}

for url in "\${URLS[@]}"; do
  code=$(curl -s -o /dev/null -w '%{http_code}' --max-time 10 "$url")
  if [[ $code =~ ^[23] ]]; then status=UP; else status=DOWN; fi
  key=$(printf '%s' "$url" | md5sum | cut -c1-16)
  prev=$(cat "$STATE_DIR/$key" 2>/dev/null || echo UP)
  if [ "$status" != "$prev" ]; then notify "[$status] $url (HTTP $code)"; fi
  echo "$status" > "$STATE_DIR/$key"
  echo "$(date -Is) $status $code $url"
done
`;
}
