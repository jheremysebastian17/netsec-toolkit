// Generates a read-only Bash audit script for Linux hardening. Pure functions, no DOM.

export const CHECKS = [
  { id: 'ssh_root', name: 'SSH root login disabled', code: `
c_ssh_root() {
  local v; v=$(sshd -T 2>/dev/null | awk '/^permitrootlogin/{print $2}')
  case "$v" in
    no) rec PASS "SSH root login" "PermitRootLogin no" ;;
    prohibit-password|without-password) rec WARN "SSH root login" "Root may log in with keys ($v)" ;;
    "") rec INFO "SSH root login" "sshd not installed or not readable" ;;
    *) rec FAIL "SSH root login" "PermitRootLogin $v - set it to 'no'" ;;
  esac
}` },
  { id: 'ssh_password', name: 'SSH password authentication disabled', code: `
c_ssh_password() {
  local v; v=$(sshd -T 2>/dev/null | awk '/^passwordauthentication/{print $2}')
  case "$v" in
    no) rec PASS "SSH password auth" "Key-based login only" ;;
    "") rec INFO "SSH password auth" "sshd not installed or not readable" ;;
    *) rec WARN "SSH password auth" "Passwords allowed - prefer keys (PasswordAuthentication no)" ;;
  esac
}` },
  { id: 'empty_passwords', name: 'No accounts with empty passwords', code: `
c_empty_passwords() {
  local u; u=$(awk -F: '($2==""){print $1}' /etc/shadow 2>/dev/null | tr '\\n' ' ')
  if [ -n "$u" ]; then rec FAIL "Empty passwords" "Accounts: $u"; else rec PASS "Empty passwords" "None found"; fi
}` },
  { id: 'uid0', name: 'Only root has UID 0', code: `
c_uid0() {
  local u; u=$(awk -F: '($3==0 && $1!="root"){print $1}' /etc/passwd | tr '\\n' ' ')
  if [ -n "$u" ]; then rec FAIL "UID 0 accounts" "Extra superusers: $u"; else rec PASS "UID 0 accounts" "Only root"; fi
}` },
  { id: 'world_writable', name: 'No world-writable files in /etc', code: `
c_world_writable() {
  local f; f=$(find /etc -xdev -type f -perm -0002 2>/dev/null | head -n 10 | tr '\\n' ' ')
  if [ -n "$f" ]; then rec FAIL "World-writable /etc files" "$f"; else rec PASS "World-writable /etc files" "None found"; fi
}` },
  { id: 'suid', name: 'SUID binaries inventory', code: `
c_suid() {
  local n; n=$(find / -xdev -type f -perm -4000 2>/dev/null | wc -l)
  if [ "$n" -gt 40 ]; then rec WARN "SUID binaries" "$n found - review unusual ones"; else rec INFO "SUID binaries" "$n found"; fi
}` },
  { id: 'ports', name: 'Listening ports (flags telnet/FTP)', code: `
c_ports() {
  local p; p=$(ss -tulnH 2>/dev/null | awk '{print $1"/"$5}' | sort -u | tr '\\n' ' ')
  if ss -tlnH 2>/dev/null | awk '{print $4}' | grep -Eq ':(21|23)$'; then
    rec FAIL "Listening ports" "Telnet or FTP is listening. All: $p"
  else rec INFO "Listening ports" "\${p:-none}"; fi
}` },
  { id: 'firewall', name: 'Firewall active', code: `
c_firewall() {
  if command -v ufw >/dev/null && ufw status 2>/dev/null | grep -q "Status: active"; then rec PASS "Firewall" "UFW active"
  elif command -v nft >/dev/null && nft list ruleset 2>/dev/null | grep -q "hook input"; then rec PASS "Firewall" "nftables input chain loaded"
  elif command -v iptables >/dev/null && iptables -S INPUT 2>/dev/null | grep -q -- "-P INPUT DROP"; then rec PASS "Firewall" "iptables INPUT policy DROP"
  else rec FAIL "Firewall" "No active host firewall detected"; fi
}` },
  { id: 'updates', name: 'Pending package updates', code: `
c_updates() {
  if command -v apt-get >/dev/null; then
    local n; n=$(apt-get -s upgrade 2>/dev/null | grep -c '^Inst')
    if [ "$n" -gt 0 ]; then rec WARN "Updates" "$n packages can be upgraded"; else rec PASS "Updates" "System up to date"; fi
  elif command -v dnf >/dev/null; then
    dnf -q check-update >/dev/null 2>&1; [ $? -eq 100 ] && rec WARN "Updates" "Updates available" || rec PASS "Updates" "System up to date"
  else rec INFO "Updates" "Unknown package manager"; fi
}` },
  { id: 'auto_updates', name: 'Automatic security updates', code: `
c_auto_updates() {
  if command -v dpkg >/dev/null; then
    dpkg -s unattended-upgrades >/dev/null 2>&1 && rec PASS "Auto updates" "unattended-upgrades installed" || rec WARN "Auto updates" "Install unattended-upgrades"
  elif command -v rpm >/dev/null; then
    rpm -q dnf-automatic >/dev/null 2>&1 && rec PASS "Auto updates" "dnf-automatic installed" || rec WARN "Auto updates" "Install dnf-automatic"
  else rec INFO "Auto updates" "Unknown package manager"; fi
}` },
];

export function buildAuditScript(ids) {
  const chosen = CHECKS.filter((c) => ids.includes(c.id));
  if (!chosen.length) throw new Error('Select at least one check');
  return `#!/usr/bin/env bash
# Linux hardening audit - generated by NetSec Toolkit.
# Read-only: it reports findings and changes nothing.
# Usage: sudo bash audit.sh [--html report.html]

HTML_OUT=""
[ "$1" = "--html" ] && HTML_OUT="\${2:-report.html}"
RESULTS=()
PASS=0; WARN=0; FAIL=0

rec() {
  local color
  case "$1" in PASS) color=32; PASS=$((PASS+1)) ;; WARN) color=33; WARN=$((WARN+1)) ;; FAIL) color=31; FAIL=$((FAIL+1)) ;; *) color=36 ;; esac
  printf '\\e[%sm[%s]\\e[0m %-28s %s\\n' "$color" "$1" "$2" "$3"
  RESULTS+=("$1|$2|$3")
}

[ "$(id -u)" -ne 0 ] && echo "Warning: not running as root - some checks will be incomplete."
echo "Hardening audit for $(hostname) - $(date)"
echo
${chosen.map((c) => c.code.trim()).join('\n\n')}

${chosen.map((c) => `c_${c.id}`).join('\n')}

echo
echo "Summary: $PASS passed, $WARN warnings, $FAIL failed"

if [ -n "$HTML_OUT" ]; then
  esc() { sed -e 's/&/\\&amp;/g' -e 's/</\\&lt;/g' -e 's/>/\\&gt;/g'; }
  {
    echo "<!doctype html><meta charset=utf-8><title>Hardening report - $(hostname)</title>"
    echo "<style>body{font:14px system-ui;margin:2rem}td,th{padding:.4rem .8rem;border-bottom:1px solid #ddd;text-align:left}.PASS{color:#1a7f37}.WARN{color:#9a6700}.FAIL{color:#cf222e}</style>"
    echo "<h1>Hardening report: $(hostname)</h1><p>$(date) &middot; $PASS passed, $WARN warnings, $FAIL failed</p><table><tr><th>Status</th><th>Check</th><th>Details</th></tr>"
    for r in "\${RESULTS[@]}"; do
      IFS='|' read -r s n d <<< "$r"
      echo "<tr><td class=$s>$s</td><td>$(printf '%s' "$n" | esc)</td><td>$(printf '%s' "$d" | esc)</td></tr>"
    done
    echo "</table>"
  } > "$HTML_OUT"
  echo "HTML report written to $HTML_OUT"
fi
`;
}
